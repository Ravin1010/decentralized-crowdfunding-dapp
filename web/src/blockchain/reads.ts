import { useQuery } from "@tanstack/react-query";
import {
  useConnection,
  usePublicClient,
  useReadContract,
  useReadContracts,
} from "wagmi";
import type { ContractFunctionReturnType } from "viem";
import { campaigns, type Campaign } from "../campaigns";
import { crowdfundingAbi } from "./abi";
import { contractConfig as config } from "./config";

export const statuses = [
  "Active",
  "Successful",
  "Failed",
  "Cancelled",
] as const;
export function parseCampaignId(value: string): bigint | undefined {
  if (!/^[1-9]\d*$/.test(value) || value.length > 78) return undefined;
  const id = BigInt(value);
  return id < 2n ** 256n ? id : undefined;
}
export function toCampaign(
  id: bigint,
  [record, status]: ContractFunctionReturnType<
    typeof crowdfundingAbi,
    "view",
    "getCampaign"
  >,
): Campaign {
  if (!statuses[status]) throw new Error("Unknown contract status");
  const date =
    record.deadline <= 8_640_000_000_000n
      ? new Date(Number(record.deadline) * 1000)
      : undefined;
  return {
    id: id.toString(),
    creator: record.creator,
    title: record.title,
    description: record.description,
    goal: record.goal,
    raised: record.amountRaised,
    status: statuses[status],
    withdrawn: record.withdrawn,
    deadlineSeconds: record.deadline,
    deadline: date
      ? date.toLocaleString("en-GB", {
          timeZone: "UTC",
          dateStyle: "medium",
          timeStyle: "short",
        }) + " UTC"
      : record.deadline.toString() + " Unix seconds",
    mode: "live",
    story: "",
    plan: "",
    cover: "community",
    coverTitle: `Campaign #${id}`,
    coverNote: "ORIGINAL ARTWORK · NO CAMPAIGN IMAGE",
  };
}
// Hidden tabs do not poll. Query keys generated by wagmi contain chain/address/args.
const policy = {
  refetchInterval: 15_000,
  refetchIntervalInBackground: false,
  staleTime: 10_000,
  retry: 1,
} as const;
function useRpcValidation() {
  const client = usePublicClient({ chainId: config.chainId });
  return useQuery({
    queryKey: ["public-rpc-chain", config.chainId, config.rpcUrl],
    queryFn: async () => {
      if (!client) throw new Error("Public client unavailable");
      if ((await client.getChainId()) !== config.chainId)
        throw new Error("RPC must serve Ethereum Sepolia (11155111).");
      return true;
    },
    enabled: config.mode === "live" && !config.error,
    ...policy,
  });
}
export function useCampaignList(page = 0) {
  const rpc = useRpcValidation();
  const count = useReadContract({
    address: config.address,
    abi: crowdfundingAbi,
    functionName: "campaignCount",
    chainId: config.chainId,
    query: {
      enabled: config.mode === "live" && rpc.isSuccess && !rpc.isError,
      ...policy,
    },
  });
  // Bound RPC work per page; IDs are deterministic and never appended to prior results.
  const start = BigInt(page) * 12n + 1n;
  const ids: bigint[] = [];
  if (count.data !== undefined)
    for (let id = start; id <= count.data && id < start + 12n; id++)
      ids.push(id);
  const details = useReadContracts({
    allowFailure: false,
    contracts: ids.map((id) => ({
      address: config.address!,
      abi: crowdfundingAbi,
      functionName: "getCampaign" as const,
      args: [id] as const,
      chainId: config.chainId,
    })),
    query: {
      enabled:
        config.mode === "live" &&
        rpc.isSuccess &&
        !rpc.isError &&
        ids.length > 0,
      ...policy,
      select: (records) =>
        records.map((record, index) => toCampaign(ids[index], record)),
    },
  });
  return {
    data: config.mode === "demo" ? campaigns : details.data,
    total: config.mode === "demo" ? 6n : count.data,
    error:
      config.error ||
      rpc.error?.message ||
      (count.error &&
        "Check the configured contract address and public RPC, then retry.") ||
      (details.error &&
        "Check the configured contract address and public RPC, then retry."),
    loading:
      config.mode === "live" &&
      !config.error &&
      (rpc.isPending ||
        count.isPending ||
        (ids.length > 0 && details.isPending)),
    refreshing: rpc.isFetching || count.isFetching || details.isFetching,
    updatedAt: details.dataUpdatedAt || count.dataUpdatedAt,
    refresh: async () => {
      if (config.error) return;
      const verified = await rpc.refetch();
      if (verified.isError || !verified.data) return;
      const latest = await count.refetch();
      if (!latest.isError && ids.length) await details.refetch();
    },
    hasNext: count.data !== undefined && start + 12n <= count.data,
  };
}
export function useCampaign(id: bigint | undefined) {
  const rpc = useRpcValidation();
  const read = useReadContract({
    address: config.address,
    abi: crowdfundingAbi,
    functionName: "getCampaign",
    args: id === undefined ? undefined : [id],
    chainId: config.chainId,
    query: {
      enabled:
        config.mode === "live" &&
        id !== undefined &&
        rpc.isSuccess &&
        !rpc.isError,
      ...policy,
      select: (record) => toCampaign(id!, record),
    },
  });
  return {
    data:
      config.mode === "demo"
        ? campaigns.find((c) => c.id === id?.toString())
        : read.data,
    error:
      config.error ||
      rpc.error?.message ||
      (read.error &&
        "Campaign not found or the contract could not be read. Check the campaign ID and retry."),
    loading:
      config.mode === "live" &&
      !config.error &&
      (rpc.isPending || read.isPending),
    refreshing: rpc.isFetching || read.isFetching,
    updatedAt: read.dataUpdatedAt,
    refresh: async () => {
      if (config.error) return;
      const verified = await rpc.refetch();
      if (!verified.isError && verified.data) await read.refetch();
    },
  };
}
export function useContribution(id: bigint) {
  const rpc = useRpcValidation();
  const { address, chainId, isConnected } = useConnection();
  const enabled =
    config.mode === "live" &&
    !!config.address &&
    !config.error &&
    rpc.isSuccess &&
    !rpc.isError &&
    isConnected &&
    chainId === config.chainId;
  const read = useReadContract({
    address: config.address,
    abi: crowdfundingAbi,
    functionName: "contributions",
    args: address ? [id, address] : undefined,
    chainId: config.chainId,
    query: { enabled, ...policy, staleTime: 0 },
  });
  // No placeholderData: previous wallet's balance is never carried across query keys.
  return {
    ...read,
    data: enabled ? read.data : undefined,
    enabled,
    rpcError: config.error || rpc.error?.message,
    isConnected,
    chainId,
  };
}
